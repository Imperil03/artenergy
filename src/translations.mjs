Object.assign(translations, JSON.parse(readFileSync(new URL('./content/homepage-copy-translations.json', import.meta.url), 'utf8')));

export function translate(value, locale='ru') {
  if (!value || locale==='ru') return value || '';
  if (translations[value]) return translations[value][locale==='en'?0:1];
  if (/^\d[\d\s]* г$/.test(value)) return value.replace(/ г$/, ' g');
  if (/^\d[\d\s]* мл$/.test(value)) return value.replace(/ мл$/, ' ml');
  if (/^\d[\d\s]* кг$/.test(value)) return value.replace(/ кг$/, ' kg');
  if (value.startsWith('от ')) return (locale==='en'?'from ':'desde ')+value.slice(3);
  if (/[А-Яа-яЁё]/.test(value)) throw new Error(`Missing ${locale} translation: ${value}`);
  return value;
}

